# Mem0 自带的提取提示词偏英文场景，这里给一段中文补充指令，
# 让它更倾向于记住中文对话里的偏好、身份、目标这类长期有效信息。
MEMORY_CUSTOM_INSTRUCTIONS = """请重点记住以下类型的信息：
- 用户的身份属性（姓名、职业、所在地、从事的领域）
- 用户的长期偏好（语言、风格、常用工具、技术栈、输出格式要求）
- 用户正在推进的项目、目标与待办
- 用户明确纠正过的事实

不要记住：一次性的寒暄、与知识库文档内容重复的信息、助手自己的回答内容。"""


def build_kb_context(chunks: List[Tuple[str, str]]) -> str:
    """
    把检索到的切片拼成提示词里的参考资料段落

    Args:
        chunks: [(片段原文, 来源描述), ...]，顺序即引用编号顺序

    Returns:
        参考资料文本；无切片时返回明确的空态说明
    """
    if not chunks:
        return "（本次没有检索到任何相关文档片段）"

    blocks = []
    for idx, (content, source) in enumerate(chunks, start=1):
        # 单个切片可能很长，裁掉空白避免提示词里出现大片空行
        blocks.append(f"[{idx}] 来源：{source}\n{content.strip()}")
    return "\n\n".join(blocks)